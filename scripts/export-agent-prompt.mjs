// Generate a readable copy from the actual runtime source; never maintain two prompts.
import { readFileSync, writeFileSync, mkdirSync } from "node:fs";
import ts from "typescript";
const compiled = { exports: {} };
new Function(
  "module",
  "exports",
  ts.transpileModule(readFileSync("src/lib/health/agent-prompt.ts", "utf8"), {
    compilerOptions: {
      module: ts.ModuleKind.CommonJS,
      target: ts.ScriptTarget.ES2022,
    },
  }).outputText,
)(compiled, compiled.exports);
const { buildHealthPrompt, buildStravaPrompt, HEALTH_PROMPT_VERSION } =
  compiled.exports;
mkdirSync("docs/agent", { recursive: true });
writeFileSync(
  "docs/agent/SYSTEM_PROMPT.md",
  `# Wolverine system prompt\n\nVersion: ${HEALTH_PROMPT_VERSION}\n\nGenerated with \`node scripts/export-agent-prompt.mjs\` from \`src/lib/health/agent-prompt.ts\`. Edit the source, then regenerate this document. The example below has personal mode and memory enabled; the runtime selects separate instructions when memory is off or fictional sample data is active. The date is illustrative, replaced each request. User data is sent separately as untrusted reference JSON.\n\n## Personal health agent\n\n${buildHealthPrompt({ sample: false, memoryEnabled: true, now: new Date("2026-09-18T12:00:00Z") })}\n\n## Separate live Strava view\n\n${buildStravaPrompt()}\n`,
);
console.log("Exported docs/agent/SYSTEM_PROMPT.md from runtime source.");

// Publish only these explicit, reviewed documents; never export user storage.
const soul = `# SOUL.md — Wolverine's behavior\n\nVersion: ${HEALTH_PROMPT_VERSION}\n\nThis is the public behavior specification used by the health agent. It describes intended behavior, not a guarantee that every model response follows it. The example is personal mode with memory enabled; sample mode and memory-off requests use their corresponding runtime branches. The illustrative UTC date is replaced for each actual request.\n\n${buildHealthPrompt({ sample: false, memoryEnabled: true, now: new Date("2026-09-18T12:00:00Z") })}\n`;
const memory = readFileSync("docs/agent/MEMORY.md", "utf8");
mkdirSync("public", { recursive: true });
writeFileSync("public/SOUL.md", soul);
writeFileSync("public/MEMORY.md", memory);
writeFileSync(
  "src/lib/health/public-documents.ts",
  `// Generated by scripts/export-agent-prompt.mjs. Contains public policy only.\nexport const publicSoul = ${JSON.stringify(soul)};\nexport const publicMemory = ${JSON.stringify(memory)};\nexport const publicPromptVersion = ${JSON.stringify(HEALTH_PROMPT_VERSION)};\n`,
);
console.log("Published public-only SOUL.md and MEMORY.md artifacts.");
